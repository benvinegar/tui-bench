import * as pty from "node-pty";
import xtermHeadless from "@xterm/headless";
import { encodeKey } from "./keys.ts";
import { takeSnapshot, type Snapshot } from "./snapshot.ts";

const { Terminal } = xtermHeadless;

export interface SessionOptions {
  command: string;
  args: string[];
  cwd: string;
  cols: number;
  rows: number;
  env?: Record<string, string>;
}

/** asciicast v2 event: [seconds, code, data]. "o" output, "i" input, "r" resize, "m" marker. */
export type CastEvent = [number, "o" | "i" | "r" | "m", string];

export interface ExitInfo {
  exitCode: number;
  signal?: number;
  at: number;
}

export type MouseButton = "left" | "middle" | "right";
export type Mods = Array<"shift" | "alt" | "ctrl">;
type Cell = { x: number; y: number };

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/**
 * A program running inside a pseudo-terminal whose output is interpreted by a
 * headless xterm.js instance, so we can read back the exact screen grid
 * (characters + colors + attributes) a human would see.
 */
export class TerminalSession {
  readonly term: InstanceType<typeof Terminal>;
  readonly proc: pty.IPty;
  readonly events: CastEvent[] = [];
  readonly startedAt = Date.now();
  exit: ExitInfo | null = null;
  private lastOutputAt = 0;
  private lastActionAt = 0;
  private emittingMouse = false;
  /** Things the scenario asked for that a real terminal would not have delivered (e.g. mouse with reporting off). */
  readonly warnings: string[] = [];
  private pendingWrites = 0;
  private sawOutput = false;
  private exitWaiters: Array<() => void> = [];

  constructor(readonly opts: SessionOptions) {
    this.term = new Terminal({
      cols: opts.cols,
      rows: opts.rows,
      allowProposedApi: true,
      scrollback: 0,
    });
    // Terminal → app: replies to capability / cursor-position queries (DA1, DSR, ...), and mouse reports
    // generated by mouse() below, which are recorded as input.
    this.term.onData((data) => {
      if (this.exit) return;
      if (this.emittingMouse) {
        this.lastActionAt = Date.now();
        this.events.push([this.elapsed(), "i", data]);
      }
      this.proc.write(data);
    });

    this.proc = pty.spawn(opts.command, opts.args, {
      name: "xterm-256color",
      cols: opts.cols,
      rows: opts.rows,
      cwd: opts.cwd,
      env: {
        PATH: process.env.PATH ?? "/usr/bin:/bin",
        HOME: process.env.HOME ?? "/tmp",
        LANG: "en_US.UTF-8",
        LC_ALL: "en_US.UTF-8",
        TERM: "xterm-256color",
        COLORTERM: "truecolor",
        TUIBENCH: "1",
        ...opts.env,
      },
    });
    this.proc.onData((data) => {
      this.sawOutput = true;
      this.lastOutputAt = Date.now();
      this.events.push([this.elapsed(), "o", data]);
      this.pendingWrites++;
      this.term.write(data, () => {
        this.pendingWrites--;
      });
    });
    this.proc.onExit(({ exitCode, signal }) => {
      this.exit = { exitCode, signal, at: Date.now() - this.startedAt };
      for (const w of this.exitWaiters.splice(0)) w();
    });
  }

  elapsed(): number {
    return (Date.now() - this.startedAt) / 1000;
  }

  /** Wait until the app has produced output and then gone quiet. */
  async waitForStartup(timeoutMs = 15000): Promise<boolean> {
    const deadline = Date.now() + timeoutMs;
    while (!this.sawOutput && !this.exit && Date.now() < deadline) await sleep(20);
    // Short cap: animated apps never go quiet, and the scenario's own steps decide what happens next.
    await this.waitIdle(250, 1000);
    return this.sawOutput;
  }

  /**
   * Wait until no output has arrived for `quietMs`, all bytes are parsed, and the
   * app isn't mid synchronized-update. Gives up after `maxMs` (animated UIs never go quiet).
   */
  async waitIdle(quietMs = 250, maxMs = 3000): Promise<void> {
    const deadline = Date.now() + maxMs;
    while (Date.now() < deadline) {
      const quiet = Date.now() - Math.max(this.lastOutputAt, this.lastActionAt) >= quietMs;
      const synced = !(this.term.modes as { synchronizedOutputMode?: boolean }).synchronizedOutputMode;
      if (quiet && this.pendingWrites === 0 && synced) return;
      if (this.exit && this.pendingWrites === 0) return;
      await sleep(15);
    }
    // Make sure whatever arrived is at least parsed before reading the grid.
    while (this.pendingWrites > 0) await sleep(5);
  }

  write(data: string): void {
    if (this.exit) return;
    this.lastActionAt = Date.now();
    this.events.push([this.elapsed(), "i", data]);
    this.proc.write(data);
  }

  async press(keys: string[], delayMs = 60): Promise<void> {
    for (const k of keys) {
      this.write(encodeKey(k, this.term.modes.applicationCursorKeysMode));
      // A lone ESC is ambiguous with the start of an escape sequence; give parsers time.
      await sleep(k.toLowerCase().startsWith("esc") ? Math.max(delayMs, 120) : delayMs);
    }
  }

  async type(text: string, delayMs = 25): Promise<void> {
    for (const ch of text) {
      this.write(ch === "\n" ? "\r" : ch);
      await sleep(delayMs);
    }
  }

  paste(text: string): void {
    const bracketed = this.term.modes.bracketedPasteMode;
    this.write(bracketed ? `\x1b[200~${text}\x1b[201~` : text);
  }

  /**
   * Send one mouse event through xterm.js's own mouse encoder, so the app receives exactly what a real
   * xterm would: nothing unless it enabled mouse reporting, motion only in the tracking modes that report
   * it, encoded in the protocol it asked for (usually SGR). Cells are 0-based. Returns whether it was sent.
   */
  mouse(ev: { x: number; y: number; button: MouseButton | "none" | "wheel"; action: "down" | "up" | "move" | "wheel-up" | "wheel-down"; mods?: Mods }): boolean {
    const core = (this.term as unknown as { _core: { coreMouseService: { triggerMouseEvent(e: object): boolean; activeProtocol: string } } })._core;
    const button = { left: 0, middle: 1, right: 2, none: 3, wheel: 4 }[ev.button];
    const action = { up: 0, down: 1, "wheel-up": 0, "wheel-down": 1, move: 32 }[ev.action];
    this.emittingMouse = true;
    try {
      return core.coreMouseService.triggerMouseEvent({
        col: ev.x,
        row: ev.y,
        x: 0,
        y: 0,
        button,
        action,
        shift: !!ev.mods?.includes("shift"),
        alt: !!ev.mods?.includes("alt"),
        ctrl: !!ev.mods?.includes("ctrl"),
      });
    } finally {
      this.emittingMouse = false;
    }
  }

  private mouseProtocol(): string {
    return (this.term as unknown as { _core: { coreMouseService: { activeProtocol: string } } })._core.coreMouseService.activeProtocol;
  }

  private warnIfNoMouse(what: string): boolean {
    if (this.mouseProtocol() !== "NONE") return false;
    this.warnings.push(`${what} was not delivered: the app has not enabled mouse reporting`);
    return true;
  }

  async click(x: number, y: number, opts: { button?: MouseButton; count?: number; mods?: Mods } = {}): Promise<void> {
    if (this.warnIfNoMouse(`click at ${x},${y}`)) return;
    const button = opts.button ?? "left";
    for (let i = 0; i < (opts.count ?? 1); i++) {
      this.mouse({ x, y, button, action: "down", mods: opts.mods });
      await sleep(30);
      this.mouse({ x, y, button, action: "up", mods: opts.mods });
      await sleep(opts.count && opts.count > 1 ? 60 : 30);
    }
  }

  /** Press at `from`, move through every cell on the way to `to` (as a hand-held mouse would), release at `to`. */
  async drag(from: Cell, to: Cell, opts: { button?: MouseButton; mods?: Mods } = {}): Promise<void> {
    if (this.warnIfNoMouse(`drag from ${from.x},${from.y}`)) return;
    const button = opts.button ?? "left";
    this.mouse({ ...from, button, action: "down", mods: opts.mods });
    await sleep(30);
    const steps = Math.max(Math.abs(to.x - from.x), Math.abs(to.y - from.y), 1);
    for (let i = 1; i <= steps; i++) {
      const x = Math.round(from.x + ((to.x - from.x) * i) / steps);
      const y = Math.round(from.y + ((to.y - from.y) * i) / steps);
      this.mouse({ x, y, button, action: "move", mods: opts.mods });
      await sleep(12);
    }
    this.mouse({ ...to, button, action: "up", mods: opts.mods });
    await sleep(30);
  }

  async scroll(x: number, y: number, direction: "up" | "down", amount = 1): Promise<void> {
    if (this.warnIfNoMouse(`scroll at ${x},${y}`)) return;
    for (let i = 0; i < amount; i++) {
      this.mouse({ x, y, button: "wheel", action: direction === "up" ? "wheel-up" : "wheel-down" });
      await sleep(25);
    }
  }

  async hover(x: number, y: number): Promise<void> {
    if (this.warnIfNoMouse(`hover at ${x},${y}`)) return;
    if (!["ANY"].includes(this.mouseProtocol())) {
      this.warnings.push(`hover at ${x},${y} was not delivered: the app only enabled click/drag reporting, not all-motion (1003)`);
      return;
    }
    this.mouse({ x, y, button: "none", action: "move" });
    await sleep(30);
  }

  resize(cols: number, rows: number): void {
    this.lastActionAt = Date.now();
    this.events.push([this.elapsed(), "r", `${cols}x${rows}`]);
    this.term.resize(cols, rows);
    if (!this.exit) this.proc.resize(cols, rows);
  }

  snapshot(name: string): Snapshot {
    this.events.push([this.elapsed(), "m", name]);
    return takeSnapshot(this.term, name, Date.now() - this.startedAt);
  }

  async waitForExit(timeoutMs: number): Promise<boolean> {
    if (this.exit) return true;
    await Promise.race([new Promise<void>((r) => this.exitWaiters.push(r)), sleep(timeoutMs)]);
    return this.exit !== null;
  }

  /** Raw asciicast v2 document of everything that happened in this session. */
  toCast(title: string): string {
    const header = {
      version: 2,
      width: this.opts.cols,
      height: this.opts.rows,
      timestamp: Math.floor(this.startedAt / 1000),
      title,
      env: { TERM: "xterm-256color" },
    };
    return [JSON.stringify(header), ...this.events.map((e) => JSON.stringify([+e[0].toFixed(4), e[1], e[2]]))].join("\n") + "\n";
  }

  async kill(): Promise<void> {
    if (this.exit) return;
    try {
      this.proc.kill("SIGTERM");
    } catch {}
    if (!(await this.waitForExit(1500))) {
      try {
        this.proc.kill("SIGKILL");
      } catch {}
      await this.waitForExit(1000);
    }
  }

  dispose(): void {
    this.term.dispose();
  }
}
